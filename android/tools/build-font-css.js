"use strict";

// Generates www/css/fonts.css from the font files in www/fonts/.
//
// The @font-face weight range must match the font's actual variable axis. Noto
// is not uniform here - most Indic Serif faces carry wght 400-700 while a few
// start lower - and declaring a range the file does not have makes browsers
// synthesise weights instead of interpolating them. So the range is read out of
// each file's fvar table rather than assumed.
//
// No dependencies; the fvar table is parsed directly.
// Run:  node android/tools/build-font-css.js

const fs = require("fs");
const path = require("path");

const appDir = path.resolve(__dirname, "..");
const fontsDir = path.join(appDir, "www/fonts");
const outFile = path.join(appDir, "www/css/fonts.css");

// Reads the variable weight axis. Returns null for a static font.
function weightAxis(file) {
  const d = fs.readFileSync(file);
  const numTables = d.readUInt16BE(4);
  let fvar = null;
  for (let i = 0; i < numTables; i++) {
    const off = 12 + 16 * i;
    if (d.toString("latin1", off, off + 4) === "fvar") {
      fvar = d.readUInt32BE(off + 8);
      break;
    }
  }
  if (fvar === null) return null;

  const axesOffset = d.readUInt16BE(fvar + 4);
  const axisCount = d.readUInt16BE(fvar + 8);
  const axisSize = d.readUInt16BE(fvar + 10);
  for (let i = 0; i < axisCount; i++) {
    const a = fvar + axesOffset + i * axisSize;
    if (d.toString("latin1", a, a + 4) !== "wght") continue;
    return {
      min: Math.round(d.readInt32BE(a + 4) / 65536),
      max: Math.round(d.readInt32BE(a + 12) / 65536)
    };
  }
  return null;
}

const files = fs.existsSync(fontsDir)
  ? fs.readdirSync(fontsDir).filter(f => f.endsWith(".ttf")).sort()
  : [];

if (!files.length) {
  console.error("No fonts in www/fonts/. Run android/tools/fetch-fonts.sh first.");
  process.exit(1);
}

const blocks = [];
const summary = [];
for (const file of files) {
  // NotoSerifDevanagari-var.ttf -> family "Noto Serif Devanagari"
  const m = /^NotoSerif(.+)-var\.ttf$/.exec(file);
  if (!m) {
    console.error("skipping unrecognised filename: " + file);
    continue;
  }
  const script = m[1];
  const family = "Noto Serif " + script;
  const axis = weightAxis(path.join(fontsDir, file));
  const range = axis ? axis.min + " " + axis.max : "400";
  const kb = Math.round(fs.statSync(path.join(fontsDir, file)).size / 1024);

  blocks.push(
    "@font-face {\n" +
    '  font-family: "' + family + '";\n' +
    '  src: url("../fonts/' + file + '") format("truetype-variations");\n' +
    "  font-weight: " + range + ";\n" +
    "  font-style: normal;\n" +
    // The reader shows one script at a time, so swapping in late is better than
    // a blank paragraph while the face loads.
    "  font-display: swap;\n" +
    // Only this script's block is ever drawn from this file; the hint lets the
    // browser skip downloading faces the current passage cannot use.
    "  unicode-range: " + unicodeRangeFor(script) + ";\n" +
    "}"
  );
  summary.push("  " + family.padEnd(26) + range.padEnd(9) + kb + " KB");
}

// Unicode block per script, so a face is only fetched when its script is shown.
function unicodeRangeFor(script) {
  return {
    Devanagari: "U+0900-097F, U+A8E0-A8FF",
    Bengali:    "U+0980-09FF",
    Gurmukhi:   "U+0A00-0A7F",
    Gujarati:   "U+0A80-0AFF",
    Oriya:      "U+0B00-0B7F",
    Tamil:      "U+0B80-0BFF",
    Telugu:     "U+0C00-0C7F",
    Kannada:    "U+0C80-0CFF",
    Malayalam:  "U+0D00-0D7F"
  }[script] || "U+0000-10FFFF";
}

const css =
  "/* Generated by android/tools/build-font-css.js - do not edit.\n" +
  " * Regenerate after changing www/fonts/:\n" +
  " *     node android/tools/build-font-css.js\n" +
  " *\n" +
  " * Family names must match fontStackFor() in js/typography.js.\n" +
  " * Weight ranges are read from each file's own fvar axis. */\n\n" +
  blocks.join("\n\n") + "\n";

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, css);

console.log("wrote www/css/fonts.css\n");
console.log("  family".padEnd(28) + "weight".padEnd(9) + "size");
console.log(summary.join("\n"));
